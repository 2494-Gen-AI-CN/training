#!/usr/bin/env python3
"""Generate the WEEKS/PHASES block in docs/index.html from harness/curriculum.json.

The site stays zero-build: this script rewrites ONLY the region between
<!-- WEEKS:BEGIN --> and <!-- WEEKS:END --> in docs/index.html and the result is
committed. tests/test_curriculum.py asserts the committed block equals render().

Usage:
    python harness/build_index.py          # rewrite docs/index.html in place
    python harness/build_index.py --check  # exit 1 if docs/index.html is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CURRICULUM = ROOT / "harness" / "curriculum.json"
INDEX = ROOT / "docs" / "index.html"
BEGIN = "<!-- WEEKS:BEGIN -->"
END = "<!-- WEEKS:END -->"


def load_curriculum() -> dict:
    return json.loads(CURRICULUM.read_text(encoding="utf-8"))


def day_paths(week: dict, day: dict) -> dict:
    """Every per-day path, derived from week.dir + day.slug (single naming rule)."""
    rel = f"{week['dir']}/{day['slug']}"
    return {
        "rel": rel,
        "page": f"weeks/{rel}.html",            # relative to docs/
        "page_fs": ROOT / "docs" / "weeks" / f"{rel}.html",
        "demos": ROOT / "demos" / rel,
        "exercise": ROOT / "exercises" / rel,
        "trainer": ROOT / "trainer" / rel,
        "research": ROOT / "harness" / "research" / f"{rel}.md",
    }


def _js(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(cur: dict | None = None) -> str:
    cur = cur or load_curriculum()
    repo = json.loads((ROOT / "harness" / "config.json").read_text(encoding="utf-8"))
    repo_url = repo.get("repoUrl", "").rstrip("/")
    branch = repo.get("repoBranch", "main")
    lines = [BEGIN, "<script>", "// Generated by harness/build_index.py from harness/curriculum.json — do not edit by hand.", "window.PHASES = {"]
    for key, ph in cur["phases"].items():
        lines.append(f"  {_js(key)}: {{ label:{_js(ph['label'])}, c:{_js(ph['c'])} }},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    lines.append("window.PROJECTS = " + _js(cur["projects"]) + ";")
    lines.append("window.WEEKS = [")
    for w in cur["weeks"]:
        lines.append(f"  {{ w:{w['week']}, phase:{_js(w['phase'])}, project:{_js(w['project'])}, title:{_js(w['theme'])}, days:[")
        for d in w["days"]:
            p = day_paths(w, d)
            entry = {"t": d["title"], "s": d.get("subtitle", ""), "id": d["id"]}
            if d.get("status") == "live":
                entry["href"] = p["page"]
                entry["demo"] = f"{repo_url}/tree/{branch}/demos/{p['rel']}"
                entry["ex"] = f"{repo_url}/tree/{branch}/exercises/{p['rel']}"
            if d.get("kind") == "review":
                entry["review"] = True
            if d.get("feedback"):
                entry["feedback"] = True
            lines.append(f"    {_js(entry)},")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("  ]},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    lines.append("</script>")
    lines.append(END)
    return "\n".join(lines)


def splice(html: str, block: str) -> str:
    start = html.index(BEGIN)
    end = html.index(END) + len(END)
    return html[:start] + block + html[end:]


def main(argv: list[str]) -> int:
    block = render()
    html = INDEX.read_text(encoding="utf-8")
    if BEGIN not in html or END not in html:
        print(f"markers missing in {INDEX}", file=sys.stderr)
        return 2
    new_html = splice(html, block)
    if "--check" in argv:
        if new_html != html:
            print("docs/index.html is stale — run: python harness/build_index.py", file=sys.stderr)
            return 1
        print("docs/index.html is in sync")
        return 0
    if new_html != html:
        INDEX.write_text(new_html, encoding="utf-8")
        print("docs/index.html updated")
    else:
        print("docs/index.html already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
