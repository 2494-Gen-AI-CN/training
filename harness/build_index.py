#!/usr/bin/env python3
"""Generate the CAL/PHASES/PROJECTS/SPRINTS/WEEKS block in docs/index.html from harness/curriculum.json.

The site stays zero-build: this script rewrites ONLY the region between
<!-- WEEKS:BEGIN --> and <!-- WEEKS:END --> in docs/index.html and the result is
committed. tests/test_curriculum.py asserts the committed block equals render().

Calendar rule (D-0013, D-0014): every date derives from curriculum.startDate.
Week 1's Monday is startDate minus its weekday; week w slot n is that Monday
+ 7*(w-1) + (n-1) days. A slot whose date is in curriculum.holidays must be
{"day": n, "kind": "holiday"}; its label comes from the holidays list. The
weekly feedback form falls on the last teaching day of each week (derived).
This module is also imported by harness/args_for.py and the tests, so the
helpers below are the only place calendar arithmetic lives.

Usage:
    python harness/build_index.py          # rewrite docs/index.html in place
    python harness/build_index.py --check  # exit 1 if docs/index.html is stale
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CURRICULUM = ROOT / "harness" / "curriculum.json"
INDEX = ROOT / "docs" / "index.html"
BEGIN = "<!-- WEEKS:BEGIN -->"
END = "<!-- WEEKS:END -->"
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri"]
GENERATED_MARK = "// Generated by harness/build_index.py from harness/curriculum.json — do not edit by hand."


def load_curriculum() -> dict:
    return json.loads(CURRICULUM.read_text(encoding="utf-8"))


# ---------------------------------------------------------------- calendar
def grid_start(cur: dict) -> dt.date:
    """Monday of week 1 (startDate may be any weekday, e.g. a Tuesday after a holiday)."""
    start = dt.date.fromisoformat(cur["startDate"])
    return start - dt.timedelta(days=start.weekday())


def slot_date(cur: dict, week_no: int, slot: int) -> dt.date:
    """Calendar date of weekday slot `slot` (1=Mon .. 5=Fri) in week `week_no` (1-based)."""
    if not 1 <= slot <= 5:
        raise ValueError(f"slot must be 1..5, got {slot}")
    return grid_start(cur) + dt.timedelta(weeks=week_no - 1, days=slot - 1)


def week_span(cur: dict, week_no: int) -> tuple[dt.date, dt.date]:
    return slot_date(cur, week_no, 1), slot_date(cur, week_no, 5)


def holiday_map(cur: dict) -> dict[dt.date, dict]:
    return {dt.date.fromisoformat(h["date"]): h for h in cur.get("holidays", [])}


def date_label(d: dt.date, year: bool = False) -> str:
    """'Tue Oct 13' (or 'Tue Oct 13, 2026')."""
    s = f"{WEEKDAYS[d.weekday()]} {d.strftime('%b')} {d.day}"
    return f"{s}, {d.year}" if year else s


def expand_week(cur: dict, week: dict) -> dict:
    """Week with every slot dated. Each item: {slot, date, weekday, kind, label?, day?}.

    Raises ValueError when a holiday slot and the holidays list disagree, so a
    stale curriculum cannot render.
    """
    hols = holiday_map(cur)
    start, end = week_span(cur, week["week"])
    slots = []
    for d in week["days"]:
        date = slot_date(cur, week["week"], d["day"])
        is_hol = d.get("kind") == "holiday"
        if is_hol != (date in hols):
            raise ValueError(f"week {week['week']} day {d['day']} ({date}) kind={d.get('kind')} but holidays={'has' if date in hols else 'lacks'} that date")
        item = {"slot": d["day"], "date": date, "weekday": WEEKDAYS[date.weekday()], "kind": d.get("kind")}
        if is_hol:
            item["label"] = hols[date]["label"]
        else:
            item["day"] = d
        slots.append(item)
    return {"week": week["week"], "start": start, "end": end, "slots": slots}


def teaching_days(week: dict) -> list[dict]:
    return [d for d in week["days"] if d.get("kind") != "holiday"]


def last_teaching_day(week: dict) -> dict:
    return teaching_days(week)[-1]


def is_feedback(week: dict, day: dict) -> bool:
    """The weekly feedback form runs on the last teaching day of the week (D-0014)."""
    return day.get("kind") != "holiday" and day["day"] == last_teaching_day(week)["day"]


def day_paths(week: dict, day: dict) -> dict:
    """Every per-day path, derived from week.dir + day.slug (single naming rule)."""
    rel = f"{week['dir']}/{day['slug']}"
    return {
        "rel": rel,
        "page": f"weeks/{rel}.html",            # relative to docs/
        "page_fs": ROOT / "docs" / "weeks" / f"{rel}.html",
        "trainer": ROOT / "trainer" / rel,
        "research": ROOT / "harness" / "research" / f"{rel}.md",
    }


# ---------------------------------------------------------------- render
def _js(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def _project_marks(cur: dict) -> dict:
    """Calendar marks from the projects drop zone (D-0065); never blocks the index.

    A broken spec is skipped with a stderr warning (strict=False); the hard failure
    lives in --check, the tests and drift_check. A checkout without the generator
    renders no marks, so args_for.py and close_day.py keep working.
    """
    empty = {"due": {}, "cp": {}, "sprints": []}
    try:
        import build_projects  # late import: it imports this module
    except ModuleNotFoundError as err:
        if err.name != "build_projects":  # a broken import inside the generator is a bug, not an absent module
            raise
        return empty
    specs = build_projects.load_specs(cur=cur, strict=False)
    marks = build_projects.calendar_marks(specs, cur)
    return {"due": marks.get("due") or {}, "cp": marks.get("cp") or {}, "sprints": marks.get("sprints") or []}


def render(cur: dict | None = None) -> str:
    cur = cur or load_curriculum()
    marks = _project_marks(cur)
    lines = [BEGIN, "<script>", GENERATED_MARK]
    lines.append("window.CAL = " + _js({
        "startDate": cur["startDate"], "endDate": cur["endDate"], "timezone": cur["timezone"],
        "holidays": cur["holidays"],
    }) + ";")
    lines.append("window.PHASES = {")
    for key, ph in cur["phases"].items():
        lines.append(f"  {_js(key)}: {{ label:{_js(ph['label'])}, c:{_js(ph['c'])} }},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    lines.append("window.PROJECTS = " + _js(cur["projects"]) + ";")
    # D-0065: one span bar per visible sprint (ISO start/end); [] when none.
    lines.append("window.SPRINTS = " + _js(marks["sprints"]) + ";")
    lines.append("window.WEEKS = [")
    for w in cur["weeks"]:
        ew = expand_week(cur, w)
        lines.append(f"  {{ w:{w['week']}, phase:{_js(w['phase'])}, project:{_js(w['project'])}, title:{_js(w['theme'])}, "
                     f"start:{_js(ew['start'].isoformat())}, end:{_js(ew['end'].isoformat())}, days:[")
        for s in ew["slots"]:
            if s["kind"] == "holiday":
                entry = {"kind": "holiday", "date": s["date"].isoformat(), "label": s["label"]}
            else:
                d = s["day"]
                p = day_paths(w, d)
                entry = {"t": d["title"], "s": d.get("subtitle", ""), "id": d["id"], "date": s["date"].isoformat()}
                # D-0052: only live days are linked; an authored day's page exists but stays unlinked (hidden week, not access control).
                if d.get("status") == "live":
                    entry["href"] = p["page"]
                if d.get("kind") == "review":
                    entry["review"] = True
                if is_feedback(w, d):
                    entry["feedback"] = True
                # D-0065: flag pills for a sprint due day / an official checkpoint, only when present.
                iso = s["date"].isoformat()
                if marks["due"].get(iso):
                    entry["due"] = marks["due"][iso]
                if marks["cp"].get(iso):
                    entry["cp"] = marks["cp"][iso]
            lines.append(f"    {_js(entry)},")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("  ]},")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("];")
    lines.append("</script>")
    lines.append(END)
    return "\n".join(lines)


def splice(html: str, block: str) -> str:
    start = html.index(BEGIN)
    end = html.index(END) + len(END)
    return html[:start] + block + html[end:]


def main(argv: list[str]) -> int:
    block = render()
    html = INDEX.read_text(encoding="utf-8")
    if BEGIN not in html or END not in html:
        print(f"markers missing in {INDEX}", file=sys.stderr)
        return 2
    new_html = splice(html, block)
    if "--check" in argv:
        if new_html != html:
            print("docs/index.html is stale — run: python harness/build_index.py", file=sys.stderr)
            return 1
        print("docs/index.html is in sync")
        # The exit-criteria pages (D-0063) link live days only, so they go stale with the same curriculum edits.
        import build_exit_pages  # late import: it imports this module
        problems = build_exit_pages.check()
        for p in problems:
            print(f"{p} — run: python harness/build_exit_pages.py", file=sys.stderr)
        if problems:
            return 1
        print("docs/exit-criteria in sync")
        # The projects pages (D-0065): spec grammar, dates and the generated pages.
        import build_projects  # late import: it imports this module
        problems = build_projects.check()
        for p in problems:
            print(f"{p} — run: python harness/build_projects.py", file=sys.stderr)
        if problems:
            return 1
        print("docs/projects in sync")
        return 0
    if new_html != html:
        INDEX.write_text(new_html, encoding="utf-8", newline="\n")
        print("docs/index.html updated")
    else:
        print("docs/index.html already up to date")
    # The exit-criteria pages (D-0063) link live days only: rebuilt wherever the index is.
    import build_exit_pages  # late import: it imports this module
    if build_exit_pages.build(quiet=True):
        print("docs/exit-criteria updated")
    # The projects pages (D-0065) share the site ?v= and nav: rebuilt wherever the index is.
    # A broken spec or a missing `markdown` package is a warning here (the tracker still rebuilds); --check,
    # the tests and drift_check.py are where it fails hard.
    import build_projects  # late import: it imports this module
    try:
        if build_projects.build(quiet=True):
            print("docs/projects updated")
    except (build_projects.SpecError, ModuleNotFoundError) as err:
        print(f"docs/projects NOT rebuilt: {err} (run: python harness/build_projects.py --validate)", file=sys.stderr)
    # The work tracker reads the same curriculum (D-0035): whoever rebuilds the index rebuilds it too.
    import build_tracker  # late import: build_tracker imports this module
    if build_tracker.build(quiet=True):
        print("tracker.html updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
