#!/usr/bin/env python3
"""Format checks for one week's demo walkthroughs (D-0055; supersedes the both-ways contract of D-0030/D-0033).

A demo is a WALKTHROUGH the trainer types in front of the room for one demo block (AM or PM):
trainer/week-WW/demos/NN-<slug>.md, format harness/templates/demo-script.md, numbered 01.. across the
week in ladder order. The answer key is the demo repo (config.json demoRepo) at the block's commit on the
week's prep branch; nothing is checked both ways here. The demos critic runs that commit.

Checks (stdlib only; the demos critic, harness/plan_check.py, harness/args_for.py and tests call this):
  name     - NN-<slug>.md; the title line names the same NN-<slug>
  header   - five blockquote fields ("> **Label:** value") above the first "## ": Objective, Time, Audience,
             Prerequisite reading, Thread; Time = "N min ..." within metrics.demos.minutesPerBlockMin..Max and
             equal to the sum of the step minutes; Thread = `<id>` — commit `<msg>` on top of `<NN-slug>` |
             `<id>` — commit `<msg>`, starts cold | standalone — starts cold
  steps    - "## Step n — title (M min[, no code])" numbered 1..n within stepsPerBlockMin..Max; every step
             with a ```python or ```bash fence states its cwd:; the Presenter cheat-sheet has one row per step
  sections - Common pitfalls / What we did NOT cover (intentional) / End-of-demo wrap-up / Sequence pointer;
             NOT-covered bullets read "- <topic>: <where>. <reason>." (D-0039)
  commit   - a thread block's last step commits with the Thread line's message in a ```bash fence
  typed    - non-blank python lines + bash commands per block <= maxTypedLinesPerBlock
  folder   - files numbered 01..NN contiguously; README.md present (generated by harness/series_readme.py)

Usage:
    python harness/demo_check.py trainer/week-02/demos            # the week folder
    python harness/demo_check.py trainer/week-02/demos/03-x.md    # one walkthrough
Exit 1 with one problem per line when anything fails; exit 0 and "OK" otherwise.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "harness" / "metrics.json"

SCRIPT_RE = re.compile(r"^(\d{2})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
TITLE_RE = re.compile(r"^# Demo: .+\(`([a-z0-9-]+|standalone)` -> `(\d{2}-[a-z0-9-]+)`\)\s*$", re.M)
HEADER_FIELDS = ["Objective", "Time", "Audience", "Prerequisite reading", "Thread"]
FIELD_RE = re.compile(r"^> \*\*([A-Za-z][A-Za-z /-]*?):\*\*\s*(.*)$")
CONT_RE = re.compile(r"^> (?!\*\*)(.*)$")
THREAD_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
THREAD_LINE_RE = re.compile(r"^`([a-z0-9]+(?:-[a-z0-9]+)*)` — commit `([^`]+)`(?: on top of `(\d{2}-[a-z0-9-]+)`|, starts cold)$")
STANDALONE_LINE_RE = re.compile(r"^standalone — starts cold$")
STEP_RE = re.compile(r"^## Step (\d+)\b.*\((\d+) min[^)]*\)\s*$", re.M)
CHEAT_HEAD = "## Presenter cheat-sheet"
REQUIRED_SECTIONS = ["## Common pitfalls", "## What we did NOT cover (intentional)", "## End-of-demo wrap-up", "## Sequence pointer"]
FENCE_RE = re.compile(r"^```([^\n`]*)\n(.*?)^```\s*$", re.M | re.S)
CWD_RE = re.compile(r"^cwd:\s*\S", re.M)
DELIVERY_RE = re.compile(r"^> \*\*DELIVERY RECORD \((\d{4}-\d{2}-\d{2})\)\*\*", re.M)


def _fences(text: str) -> list[tuple[str, str]]:
    """[(info string, body)] for every fenced block, in order."""
    return [(m.group(1).strip(), m.group(2)) for m in FENCE_RE.finditer(text)]


def _lines(body: str) -> list[str]:
    return [ln.strip() for ln in body.splitlines() if ln.strip()]


def _head_text(text: str) -> str:
    return text.split("\n## ", 1)[0]


def _header(text: str) -> dict[str, str]:
    """{Label: value} from the "> **Label:** value" lines above the first "## "; continuation "> " lines join."""
    out: dict[str, str] = {}
    cur = None
    for ln in _head_text(text).splitlines():
        m = FIELD_RE.match(ln)
        if m:
            cur = m.group(1).strip()
            out[cur] = m.group(2).strip()
            continue
        c = CONT_RE.match(ln)
        if c and cur and c.group(1).strip():
            out[cur] = (out[cur] + " " + c.group(1).strip()).strip()
        elif not c:
            cur = None
    return out


def thread_info(hdr: dict[str, str]) -> tuple[str, str, str] | None:
    """(thread id or 'standalone', commit message or '', starts-from block name or 'cold'); None when malformed."""
    line = hdr.get("Thread", "").strip()
    if STANDALONE_LINE_RE.match(line):
        return "standalone", "", "cold"
    m = THREAD_LINE_RE.match(line)
    if not m:
        return None
    return m.group(1), m.group(2), m.group(3) or "cold"


def time_minutes(hdr: dict[str, str]) -> int | None:
    m = re.match(r"^(\d+) min\b", hdr.get("Time", ""))
    return int(m.group(1)) if m else None


def _steps(text: str) -> list[tuple[int, int, str]]:
    """[(n, minutes, section body)] for every '## Step n' heading."""
    heads = list(STEP_RE.finditer(text))
    out = []
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        body = text[m.end():end]
        body = body.split("\n## ", 1)[0]  # stop at the next non-step heading
        out.append((int(m.group(1)), int(m.group(2)), body))
    return out


def cheat_rows(text: str) -> list[int]:
    """Step numbers in the Presenter cheat-sheet table, in order."""
    m = re.search(r"^## Presenter cheat-sheet\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return []
    nums = []
    for ln in m.group(1).splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")] if ln.strip().startswith("|") else []
        if cells and cells[0].isdigit():
            nums.append(int(cells[0]))
    return nums


def typed_line_count(text: str) -> int:
    """Lines the trainer types in one block: python lines plus bash commands (comments and blanks dropped)."""
    n = 0
    for info, body in _fences(text):
        parts = info.split()
        if parts[:1] == ["python"]:
            n += len(_lines(body))
        elif parts[:1] == ["bash"]:
            n += len([ln for ln in _lines(body) if not ln.startswith("#")])
    return n


def commit_lines(body: str) -> list[str]:
    """Commit messages of every `git commit -m "..."` in the ```bash fences of a step body."""
    out = []
    for info, fb in _fences(body):
        if info.split()[:1] == ["bash"]:
            out += re.findall(r'git commit\s+(?:-a\s+)?-m\s+"([^"]*)"', fb)
    return out


def not_covered_problems(text: str) -> list[str]:
    """Bullets under 'What we did NOT cover (intentional)' that are not '- <topic>: <sentence>' (D-0039).

    One format on every script, so the list reads the same from day to day: the topic, a colon, where it goes or
    why it is out, then the reason as its own sentence. A dash between topic and note is the old format.
    """
    m = re.search(r"^## What we did NOT cover \(intentional\)\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    bad = []
    for ln in (m.group(1).splitlines() if m else []):
        if not ln.startswith("- "):
            continue
        bare = re.sub(r"`[^`\n]*`", "`c`", ln)  # a colon or a dash inside code is not a separator
        if re.search(r" (—|–|--) ", bare) or not re.match(r"^- [^:]+: \S", bare):
            bad.append(ln)
    return bad


def delivery_dates(text: str) -> list[str]:
    """Dates of the DELIVERY RECORD blockquotes appended by harness/close_day.py."""
    return DELIVERY_RE.findall(text)


def header_facts(path: Path) -> dict:
    """What other tools read off a walkthrough: name, time, thread, startsFrom, commit, objective, delivered."""
    text = path.read_text(encoding="utf-8")
    hdr = _header(text)
    ti = thread_info(hdr) or (None, None, None)
    return {"name": path.stem, "time": time_minutes(hdr), "thread": ti[0], "commit": ti[1], "startsFrom": ti[2],
            "objective": hdr.get("Objective", ""), "steps": len(_steps(text)), "delivered": delivery_dates(text)}


def check_file(path: Path, metrics: dict) -> list[str]:
    p: list[str] = []
    name = path.name
    m = SCRIPT_RE.match(name)
    if not m:
        return [f"{name}: walkthrough must be named NN-<slug>.md"]
    text = path.read_text(encoding="utf-8")
    tm = TITLE_RE.search(_head_text(text))
    if not tm:
        p.append(f"{name}: title must read '# Demo: <title> (`<thread-id>` -> `{path.stem}`)'")
    elif tm.group(2) != path.stem:
        p.append(f"{name}: title names `{tm.group(2)}`, the file is {path.stem}")
    hdr = _header(text)
    for f in HEADER_FIELDS:
        if not hdr.get(f):
            p.append(f"{name}: header field '> **{f}:**' missing or empty")
    total = time_minutes(hdr)
    if hdr.get("Time") and total is None:
        p.append(f"{name}: Time must start with 'N min'")
    lo, hi = metrics.get("minutesPerBlockMin", 0), metrics.get("minutesPerBlockMax", 10**6)
    if total is not None and not lo <= total <= hi:
        p.append(f"{name}: Time {total} min outside {lo}..{hi}")
    ti = thread_info(hdr) if hdr.get("Thread") else None
    if hdr.get("Thread") and ti is None:
        p.append(f"{name}: Thread must read `<id>` — commit `<msg>` on top of `<NN-slug>` | `<id>` — commit `<msg>`, starts cold | standalone — starts cold; got '{hdr['Thread'][:80]}'")
    if ti and tm and tm.group(1) != ti[0]:
        p.append(f"{name}: title thread `{tm.group(1)}` differs from the Thread field `{ti[0]}`")
    steps = _steps(text)
    slo, shi = metrics.get("stepsPerBlockMin", 2), metrics.get("stepsPerBlockMax", 10**6)
    if not slo <= len(steps) <= shi:
        p.append(f"{name}: {len(steps)} '## Step n — title (M min)' headings, band is {slo}..{shi}")
    if [s[0] for s in steps] != list(range(1, len(steps) + 1)):
        p.append(f"{name}: steps must be numbered 1..n in order, got {[s[0] for s in steps]}")
    if total is not None and steps and sum(s[1] for s in steps) != total:
        p.append(f"{name}: step minutes sum to {sum(s[1] for s in steps)}, header Time says {total}")
    for n, _mins, body in steps:
        if any(i.split()[:1] in (["python"], ["bash"]) for i, _ in _fences(body)) and not CWD_RE.search(body):
            p.append(f"{name}: Step {n} has a code/command block but no 'cwd:' line")
    if CHEAT_HEAD not in text:
        p.append(f"{name}: missing section '{CHEAT_HEAD}'")
    elif steps and cheat_rows(text) != [s[0] for s in steps]:
        p.append(f"{name}: Presenter cheat-sheet rows {cheat_rows(text)} must be one per step {[s[0] for s in steps]}")
    for s in REQUIRED_SECTIONS:
        if s not in text:
            p.append(f"{name}: missing section '{s}'")
    for ln in not_covered_problems(text):
        p.append(f"{name}: 'What we did NOT cover' bullet must read '- <topic>: <where it goes>. <reason>.' with no dash as the separator (D-0039): {ln[:80]}")
    if ti and ti[0] != "standalone" and steps:
        msgs = commit_lines(steps[-1][2])
        if ti[1] not in msgs:
            p.append(f"{name}: the last step must commit the block in a ```bash fence with git commit -m \"{ti[1]}\" (found {msgs or 'no commit'})")
    cap = metrics.get("maxTypedLinesPerBlock")
    if cap and typed_line_count(text) > cap:
        p.append(f"{name}: {typed_line_count(text)} typed lines > maxTypedLinesPerBlock {cap}; split the block")
    return p


def walkthroughs(demo_dir: Path) -> list[Path]:
    return sorted(f for f in demo_dir.iterdir() if f.is_file() and SCRIPT_RE.match(f.name))


def check_dir(demo_dir: Path, metrics: dict | None = None) -> list[str]:
    """All problems for one week's demo folder. Empty list = OK."""
    if metrics is None:
        metrics = json.loads(METRICS.read_text(encoding="utf-8"))["demos"]
    if not demo_dir.is_dir():
        return [f"{demo_dir}: missing"]
    p: list[str] = []
    files = walkthroughs(demo_dir)
    if not files:
        p.append(f"{demo_dir.name}: no NN-<slug>.md walkthrough")
    nums = [int(f.name[:2]) for f in files]
    if nums != list(range(1, len(nums) + 1)):
        p.append(f"{demo_dir.name}: walkthroughs must be numbered 01..NN in order across the week, got {nums}")
    for f in files:
        p += check_file(f, metrics)
    if not (demo_dir / "README.md").exists():
        p.append(f"{demo_dir.name}/README.md missing (run python harness/series_readme.py <week>)")
    return p


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    target = Path(argv[0])
    if target.is_file():
        metrics = json.loads(METRICS.read_text(encoding="utf-8"))["demos"]
        problems = check_file(target, metrics)
    else:
        problems = check_dir(target)
    for pr in problems:
        print(pr)
    print("OK" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
