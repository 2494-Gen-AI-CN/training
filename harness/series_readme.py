#!/usr/bin/env python3
"""Render one week's demo series README from its plan (D-0055).

trainer/week-WW/demos/README.md is the trainer's index of the week's walkthroughs, shaped like the series READMEs
of the reference corpus: ordered demo table, dependency graph, stop points, squeeze priorities, hard-stop rule,
scaffold bundle, run prerequisites, anti-spoiler ledger, real-world framing. Every section comes from
harness/plans/week-WW.md (harness/plan_check.py parses it); the Delivered column comes from each day's
trainer/<rel>/delivery.json. The file is generated, never hand-edited: edit the plan and rerun.

Usage:
    python harness/series_readme.py 2            # write trainer/week-02/demos/README.md
    python harness/series_readme.py 2 --check    # exit 1 when the file is missing or stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_index as bi  # noqa: E402
import plan_check as pc  # noqa: E402

ROOT = bi.ROOT
HEADER_NOTE = "<!-- Generated by harness/series_readme.py from harness/plans/week-{ww}.md (D-0055). Edit the plan, then rerun; never edit this file. -->"


def _delivery(rel: str) -> dict | None:
    f = ROOT / "trainer" / rel / "delivery.json"
    if not f.is_file():
        return None
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except ValueError:
        return None


def _delivered(rec: dict | None, name: str) -> str:
    if not rec:
        return "—"
    for b in rec.get("blocks", []):
        if b.get("name") == name:
            return f"{b.get('state', '?')} ({rec.get('date', '?')})"
    return f"day closed {rec.get('date', '?')}"


def _table(cols: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(c.replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(week: int, root: Path = ROOT) -> str:
    plan = pc.load_plan(root / "harness" / "plans" / f"week-{week:02d}.md")
    cur = bi.load_curriculum()
    wk = next(w for w in cur["weeks"] if w["week"] == week)
    ew = bi.expand_week(cur, wk)
    by_slot = {s["slot"]: s for s in ew["slots"]}
    days = {d["id"]: d for d in bi.teaching_days(wk)}
    cfg = json.loads((root / "harness" / "config.json").read_text(encoding="utf-8"))
    repo = cfg.get("demoRepo", {})
    prep = repo.get("prepBranch", "prep/week-{WW}").replace("{WW}", f"{week:02d}")
    ww = f"{week:02d}"
    blocks = pc.week_blocks(plan)
    delivery = {did: _delivery(f"{wk['dir']}/{d['slug']}") for did, d in days.items()}

    def day_label(did: str) -> str:
        d = days.get(did)
        if not d:
            return did
        s = by_slot[d["day"]]
        return f"{bi.date_label(s['date'])} ({did})"

    L: list[str] = []
    L.append(f"# Week {ww} demo series — {wk['theme']}")
    L.append("")
    L.append(HEADER_NOTE.format(ww=ww))
    L.append("")
    L.append(f"Week {week} · {ew['start'].isoformat()} to {ew['end'].isoformat()} · project {wk['project']} · "
             f"{len(blocks)} walkthrough{'s' if len(blocks) != 1 else ''}, {sum(b['minutes'] or 0 for b in blocks)} min of live code-along.")
    L.append("")
    L.append(f"Each walkthrough is one demo block (AM or PM) the trainer performs live, typed in front of the room, and ends in one commit. "
             f"The answer key is the demo repo `{repo.get('url', '')}` at that commit on branch `{prep}` (one commit per walkthrough, "
             f"in ladder order); the trainer types live on `{repo.get('branch', 'main')}`. Walkthroughs live beside this file; "
             f"the plan `harness/plans/week-{ww}.md` is the source of every section below.")
    L.append("")
    L.append("## Threads")
    L.append("")
    for t in plan["threads"]:
        L.append(f"- **`{t['id']}`** — {t['domain']}")
        L.append(f"  - Scope: {t['scope']}")
        L.append(f"  - Start state this week: {t['startState']}")
        L.append(f"  - End state this week: {t['endState']}")
    if plan["standalone"]:
        L.append("- **Standalone** (no thread): " + "; ".join(f"`{s['Walkthrough']}` ({s['Why it fits no thread']})" for s in plan["standalone"]))
    L.append("")
    L.append("## Conventions")
    L.append("")
    L.append("The rules every block follows that the block table does not spell out (D-0057); a rule applies from the walkthrough named, or from the first block.")
    L.append("")
    L.append(_table(["Convention", "Kind", "Applies from", "Rule"],
                    [[r["Convention"], r["Kind"], f"`{r['Applies from']}`", r["Rule"]] for r in plan["conventions"]]))
    L.append("")
    L.append("## Ordered demo table (calendar order)")
    L.append("")
    rows, cum = [], 0
    for b in blocks:
        cum += b["minutes"] or 0
        rows.append([str(b["n"]), day_label(b["day"]), b["slot"], f"[`{b['name']}.md`]({b['name']}.md)", str(b["minutes"] or "?"), str(cum),
                     f"`{b['commitMessage']}`" if b["commitMessage"] else "—", _delivered(delivery.get(b["day"]), b["name"])])
    L.append(_table(["#", "Day", "Slot", "Walkthrough", "Minutes", "Cumulative", "Commit", "Delivered"], rows))
    L.append("")
    L.append("## Cross-demo dependency graph")
    L.append("")
    L.append("```")
    for t in plan["threads"]:
        names = [b["Walkthrough"] for b in t["blocks"]]
        if names:
            start = t["blocks"][0]["Starts from"]
            L.append(f"{t['id']}: {start} ──► " + " ──► ".join(names))
    for s in plan["standalone"]:
        L.append(f"standalone: cold ──► {s['Walkthrough']}")
    L.append("```")
    L.append("")
    L.append("**Load-bearing (what each walkthrough guarantees for the ones after it):**")
    L.append("")
    for b in blocks:
        mf = b["mustFollow"] if b["mustFollow"] not in ("", "—", "-", "none") else "—"
        L.append(f"- `{b['name']}` (must follow {mf}): {b['guarantees']}")
    L.append("")
    L.append("## Stop points if splitting (clean boundaries to halt at)")
    L.append("")
    L.append(_table(["Walkthrough", "Clean stop point", "Resume at"],
                    [[f"`{s['Walkthrough']}`", s["Clean stop point"], s["Resume at"]] for s in plan["stopPoints"]]))
    L.append("")
    L.append("## Squeeze priorities (over budget — cut in this order)")
    L.append("")
    L.append("**Cut first:**")
    L.append("")
    L += [f"{i}. {x}" for i, x in enumerate(plan["squeeze"]["cutFirst"], 1)]
    L.append("")
    L.append("**Never cut (the lesson dies without these):**")
    L.append("")
    L += [f"- {x}" for x in plan["squeeze"]["neverCut"]]
    L.append("")
    L.append("## Hard-stop rule")
    L.append("")
    L.append(plan["hardStop"])
    L.append("")
    L.append("## Scaffold bundle (\"scaffold the rote, hand-type the lesson\")")
    L.append("")
    if plan["scaffold"]["intro"]:
        L.append(plan["scaffold"]["intro"])
        L.append("")
    L.append(_table(["Day", "Hand-out", "Pre-provided", "Why rote"],
                    [[day_label(r["Day"]), r["Hand-out"], r["Pre-provided"], r["Why rote"]] for r in plan["scaffold"]["handouts"]]))
    L.append("")
    L.append("**What never to pre-provide (hand-typed live, always):**")
    L.append("")
    L.append(_table(["Never pre-provide", "Walkthrough"], [[r["Never pre-provide"], f"`{r['Walkthrough']}`"] for r in plan["scaffold"]["never"]]))
    L.append("")
    L.append("## Run prerequisites")
    L.append("")
    L += [f"- {x}" for x in plan["prereqs"]]
    L.append("")
    L.append("## Per-day shape")
    L.append("")
    for did in days:
        body = plan["dayShape"].get(did)
        if body:
            L.append(body)
            L.append("")
    L.append("## Anti-spoiler ledger (what each day defers, on purpose)")
    L.append("")
    L.append(_table(["Day", "Defers", "To", "Why"], [[r["Day"], r["Defers"], r["To"], r["Why"]] for r in plan["spoilers"]]))
    L.append("")
    L.append("## Real-world framing and deliberate deviations")
    L.append("")
    if plan["framing"]:
        L.append(plan["framing"])
        L.append("")
    L.append(_table(["Deviation", "Workplace reality", "Pedagogical reason"],
                    [[r["Deviation"], r["Workplace reality"], r["Pedagogical reason"]] for r in plan["deviations"]]))
    L.append("")
    L.append(f"Back to the plan: `harness/plans/week-{ww}.md`. Delivery records: each walkthrough's header (appended by `harness/close_day.py`) and `trainer/<day>/delivery.json`.")
    L.append("")
    return "\n".join(L)


def target(week: int, root: Path = ROOT) -> Path:
    cur = bi.load_curriculum()
    wk = next(w for w in cur["weeks"] if w["week"] == week)
    return root / "trainer" / wk["dir"] / "demos" / "README.md"


def write(week: int, root: Path = ROOT) -> Path:
    out = target(week, root)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(week, root), encoding="utf-8")
    return out


def check(week: int, root: Path = ROOT) -> list[str]:
    out = target(week, root)
    if not out.is_file():
        return [f"{out} missing (run python harness/series_readme.py {week})"]
    if out.read_text(encoding="utf-8") != render(week, root):
        return [f"{out} is stale against harness/plans/week-{week:02d}.md or the delivery records (run python harness/series_readme.py {week})"]
    return []


def main(argv: list[str]) -> int:
    nums = [a for a in argv if a.isdigit()]
    if len(nums) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    week = int(nums[0])
    if "--check" in argv:
        problems = check(week)
        for pr in problems:
            print(pr)
        print("OK" if not problems else f"{len(problems)} problem(s)")
        return 1 if problems else 0
    if not (ROOT / "trainer").is_dir():
        print("trainer/ is not cloned here; nothing written", file=sys.stderr)
        return 2
    print(f"wrote {write(week)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
