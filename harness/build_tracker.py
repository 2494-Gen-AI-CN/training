#!/usr/bin/env python3
"""Generate tracker.html (the project work tracker, D-0035) from repo state.

tracker.html at the repo root is a LOCAL file: it is gitignored and never committed (D-0036), so
trainees browsing the public repo do not see it. Its hand-written shell (CSS + JS, no data) is the
committed template harness/templates/tracker.html; this script copies the shell and fills the region
between <!-- TRACKER:BEGIN --> and <!-- TRACKER:END --> with the data block. Edit the template, never
the generated page. When tracker.html exists, tests/test_tracker.py asserts it equals template + render(),
so any change to tracked state without a rebuild fails the suite on the machine that uses the tracker.

Nothing here reads a clock: the block is a pure function of the files below. Everything
relative to today's date (next up, overdue, readiness alarms) is computed in the browser.

Day status (D-0052): planned -> authored -> live. `authored` means every artifact exists and passed but the
page is not yet linked from the index (released the Friday before its week by harness/release_week.py);
`taught` implies live, and trainer/<rel>/delivery.json marks a day closed. Status passes through unchanged;
artifact flags are read from disk for every day, whatever its status.

Sources:
  harness/curriculum.json           calendar, days, status (planned | authored | live, D-0052), taught
  harness/plans/week-WW.md          week plans: plan_check verdict, planned walkthrough blocks per day
  harness/research/, docs/weeks/, exercises/, trainer/<rel>/, trainer/week-WW/demos/   per-day artifacts on disk
  trainer/<rel>/delivery.json       delivery record written by harness/close_day.py when a day is closed (D-0050)
  harness/config.json               threads, tracker alarm thresholds
  STATUS.md                         phase line, milestones, open items, latest log lines
  docs/process/codify-plan.md       codify stages (order table)
  decisions/README.md               decision count and latest entries
  harness/runs.jsonl                one record per workflow run (appended by harness/log_run.py)
  harness/last-tests.json           last recorded test result (harness/log_run.py tests)

trainer/ is a separate private repo. Half of the tracked state lives there, so the build refuses
to write when it is absent (and the staleness test skips), rather than recording "nothing authored".

Usage:
    python harness/build_tracker.py          # write tracker.html (creates it on a fresh clone)
    python harness/build_tracker.py --check  # exit 1 if tracker.html is missing or stale
    python harness/build_tracker.py --json   # print the data block's JSON
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_index as bi  # noqa: E402
import demo_check  # noqa: E402
import plan_check  # noqa: E402

ROOT = bi.ROOT
HARNESS = ROOT / "harness"
TRAINER = ROOT / "trainer"
TRACKER = ROOT / "tracker.html"                       # generated, gitignored (D-0036)
TEMPLATE = HARNESS / "templates" / "tracker.html"     # committed shell, empty data block
STATUS = ROOT / "STATUS.md"
CODIFY = ROOT / "docs" / "process" / "codify-plan.md"
DECISIONS = ROOT / "decisions"
RUNS = HARNESS / "runs.jsonl"
LAST_TESTS = HARNESS / "last-tests.json"
PLANS = HARNESS / "plans"
BEGIN = "<!-- TRACKER:BEGIN -->"
END = "<!-- TRACKER:END -->"
GENERATED_MARK = "// Generated by harness/build_tracker.py from repo state (D-0035) — do not edit by hand."

ISO_RE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
DAYREF_RE = re.compile(r"\bW(\d{1,2})D(\d)\b")
DECISION_ROW_RE = re.compile(r"^\| (D-\d{4}) \| (\d{4}-\d{2}-\d{2}) \| (\w+) \| (.*?) \| (.*?) \| (.*?) \|$")
MILESTONE_HEADER = "| # | Milestone | Done | Notes |"
OPEN_HEADER = "| ID | Item | Owner | Needed by | Notes |"
STAGE_HEADER = "| Order | Stage | Why first | Size |"
RUN_KINDS = ("day-fanout", "demo-series", "week-plan", "practice", "manual")


class TrainerMissing(RuntimeError):
    pass


def _short(text: str, limit: int) -> str:
    """One line, at most `limit` characters; a cut inside a `code span` closes the span before the ellipsis."""
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    cut = text[:limit - 1].rstrip()
    return cut + ("`" if cut.count("`") % 2 else "") + "…"


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split(" | ")]


def _table(text: str, header: str) -> list[list[str]]:
    """Body rows of the markdown table whose header line is exactly `header`."""
    lines = text.splitlines()
    try:
        i = lines.index(header)
    except ValueError:
        return []
    rows = []
    for ln in lines[i + 2:]:
        if not ln.startswith("|"):
            break
        rows.append(_cells(ln))
    return rows


def _unstrike(s: str) -> str:
    return s.replace("~~", "").strip()


# ---------------------------------------------------------------- STATUS.md
def parse_status(cur: dict, text: str | None = None) -> dict:
    text = STATUS.read_text(encoding="utf-8") if text is None else text
    phase = re.search(r"^\*\*Phase:\*\*\s*(.*)$", text, re.M)
    updated = re.search(r"^\*\*Last updated:\*\*\s*(\d{4}-\d{2}-\d{2})", text, re.M)
    milestones = []
    for c in _table(text, MILESTONE_HEADER):
        if len(c) < 4:
            continue
        done_cell = c[2]
        iso = ISO_RE.search(done_cell)
        state = "open" if not iso else ("done" if done_cell.strip() == iso.group(1) else "partial")
        milestones.append({"n": c[0], "title": c[1], "state": state, "done": iso.group(1) if iso else None,
                           "doneText": done_cell, "notes": _short(c[3], 260)})
    items = []
    for c in _table(text, OPEN_HEADER):
        if len(c) < 5:
            continue
        closed = c[1].startswith("~~") or c[3].lower().startswith("closed")
        due, due_from = None, None
        iso = ISO_RE.search(c[3])
        ref = DAYREF_RE.search(c[3])
        if not closed and iso:
            due, due_from = iso.group(1), "date"
        elif not closed and ref:
            try:
                due, due_from = bi.slot_date(cur, int(ref.group(1)), int(ref.group(2))).isoformat(), "day"
            except ValueError:
                pass
        items.append({"id": c[0], "item": _short(_unstrike(c[1]), 260), "owner": c[2], "neededBy": _short(c[3], 160),
                      "due": due, "dueFrom": due_from, "closed": closed, "notes": _short(c[4], 320)})
    log = []
    m = re.search(r"^## Log\s*$", text, re.M)
    if m:
        for ln in text[m.end():].splitlines():
            if ln.startswith("- "):
                log.append(_short(ln[2:], 300))
            if len(log) == 5:
                break
    return {"phase": phase.group(1).strip() if phase else "", "updated": updated.group(1) if updated else None,
            "milestones": milestones, "openItems": items, "log": log}


# ---------------------------------------------------------------- codify stages, decisions
def parse_stages(text: str | None = None) -> list[dict]:
    text = CODIFY.read_text(encoding="utf-8") if text is None else text
    out = []
    for c in _table(text, STAGE_HEADER):
        if len(c) < 4:
            continue
        done = c[0].startswith("~~")
        note = c[3].rsplit("~~", 1)[-1].strip() if done else ""
        out.append({"order": _unstrike(c[0]), "name": _unstrike(c[1]), "done": done,
                    "note": _short(note, 160), "size": "" if done else _short(c[3], 120)})
    return out


def parse_decisions() -> dict:
    rows = []
    for ln in (DECISIONS / "README.md").read_text(encoding="utf-8").splitlines():
        m = DECISION_ROW_RE.match(ln)
        if m:
            rows.append(m.groups())
    files = {p.name[:6]: p.name for p in DECISIONS.glob("D-*.md")}
    latest = [{"id": r[0], "date": r[1], "status": r[2], "decision": _short(r[3], 200), "file": files.get(r[0], "")}
              for r in rows[:8]]
    return {"count": len(rows), "accepted": sum(1 for r in rows if r[2] == "accepted"),
            "superseded": sum(1 for r in rows if r[2] == "superseded"), "latest": latest}


# ---------------------------------------------------------------- runs, tests
def load_runs() -> list[dict]:
    if not RUNS.is_file():
        return []
    return [json.loads(ln) for ln in RUNS.read_text(encoding="utf-8").splitlines() if ln.strip()]


def load_last_tests() -> dict | None:
    return json.loads(LAST_TESTS.read_text(encoding="utf-8")) if LAST_TESTS.is_file() else None


# ---------------------------------------------------------------- plans, days, threads
def _plans() -> dict[int, dict]:
    """week number -> {path, ok, problems, plan (parsed or None)} for every plan file."""
    out = {}
    if not PLANS.is_dir():
        return out
    metrics = json.loads((HARNESS / "metrics.json").read_text(encoding="utf-8"))["demos"]
    for p in sorted(PLANS.glob("week-*.md")):
        try:
            plan = plan_check.load_plan(p)
        except ValueError:
            m = re.match(r"week-(\d{2})\.md$", p.name)
            if m:
                out[int(m.group(1))] = {"path": f"harness/plans/{p.name}", "ok": False, "problems": 1, "plan": None}
            continue
        problems = plan_check.check_plan(p, metrics)
        out[plan["week"]] = {"path": f"harness/plans/{p.name}", "ok": not problems, "problems": len(problems), "plan": plan}
    return out


def _delivery(path: Path) -> dict | None:
    """Summary of trainer/<rel>/delivery.json (written by harness/close_day.py, D-0050), None when absent."""
    if not path.is_file():
        return None
    try:
        rec = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(rec, dict):
            raise ValueError("not an object")
        blocks = rec.get("blocks") if isinstance(rec.get("blocks"), list) else None
        files = rec.get("files") if isinstance(rec.get("files"), list) else []
        states = [str(b.get("state", "?")) for b in blocks] if blocks else []
        return {"date": rec.get("date"), "format": rec.get("format"),
                "blocks": len(blocks) if blocks is not None else len(files), "states": states,
                "sha": str(rec.get("demoRepoSha") or "")[:7]}
    except ValueError:
        return {"date": None, "format": "unreadable", "blocks": 0, "states": [], "sha": ""}


def _day(cur: dict, week: dict, slot: dict, plan_info: dict | None) -> dict:
    if slot["kind"] == "holiday":
        return {"slot": slot["slot"], "date": slot["date"].isoformat(), "kind": "holiday", "label": slot["label"]}
    d = slot["day"]
    p = bi.day_paths(week, d)
    rel = p["rel"]
    rows = plan_check.day_rows(plan_info["plan"], d["id"]) if plan_info and plan_info["plan"] else None
    blocks = rows["blockRows"] if rows else []
    ddir = TRAINER / week["dir"] / "demos"   # the week's walkthroughs (D-0055)
    scripts = sum(1 for b in blocks if (ddir / f"{b['name']}.md").is_file())
    planned = len(blocks) if rows else None
    minutes = None
    if rows and rows["ladderRows"]:
        minutes = sum(int(r["Minutes"]) for r in rows["ladderRows"] if r["Minutes"].isdigit())
    delivery = _delivery(p["trainer"] / "delivery.json")
    rubric = d.get("exerciseKind", "pytest") == "rubric"
    sol = p["trainer"] / "solutions"
    solutions = (sol / "RUBRIC.md").is_file() if rubric else (sol.is_dir() and any(sol.glob("*.py")))
    return {
        "slot": slot["slot"], "date": slot["date"].isoformat(), "id": d["id"], "rel": rel,
        "title": d["title"], "subtitle": d.get("subtitle", ""), "kind": d["kind"], "gate": d["gate"],
        "demoFormat": d["demoFormat"], "exerciseKind": d.get("exerciseKind", "pytest"),
        "status": d.get("status", "planned"), "taught": d.get("taught"), "feedback": bi.is_feedback(week, d),
        "subtopics": len(d["subtopics"]),
        "a": {
            "research": p["research"].is_file(),
            "demos": {"planned": planned, "scripts": scripts},
            "notes": p["page_fs"].is_file(),
            "exercise": (p["exercise"] / "README.md").is_file(),
            "runbook": (p["trainer"] / "runbook.md").is_file(),
            "solutions": bool(solutions),
            "closed": delivery is not None,
        },
        "delivery": delivery,
        "coverage": len(rows["weekPlanRows"]) if rows else None,
        "demoMinutes": minutes,
        "rows": [{"thread": b["thread"], "block": b["block"], "name": b["name"], "slot": b["slot"], "minutes": b["minutes"],
                  "startsFrom": b["startsFrom"], "commit": _short(b["commitMessage"], 80), "adds": _short(b["adds"], 180),
                  "authored": (ddir / f"{b['name']}.md").is_file()} for b in blocks],
    }


def _threads(cur: dict, config: dict, plans: dict[int, dict]) -> list[dict]:
    """The demo threads (D-0033, D-0055): every block of every planned week, with whether its walkthrough exists."""
    taught = {d["id"]: d.get("taught") for w in cur["weeks"] for d in w["days"] if d.get("kind") != "holiday"}
    wdir = {w["week"]: w["dir"] for w in cur["weeks"]}
    out = []
    for tid, t in (config.get("threads") or {}).items():
        if not isinstance(t, dict):
            continue
        blocks = []
        for wk in sorted(plans):
            plan = plans[wk]["plan"]
            if not plan:
                continue
            ddir = TRAINER / wdir.get(wk, f"week-{wk:02d}") / "demos"
            for th in plan["threads"]:
                if th["id"] != tid:
                    continue
                for r in th["blocks"]:
                    blocks.append({"week": wk, "block": r["Block"], "day": r["Day"], "name": r["Walkthrough"], "slot": r["Slot"],
                                   "authored": (ddir / f"{r['Walkthrough']}.md").is_file(), "taught": bool(taught.get(r["Day"])),
                                   "commit": _short(r["Commit message"], 80)})
        out.append({"id": tid, "domain": _short(t.get("domain", ""), 200), "project": t.get("project", ""),
                    "weeks": t.get("weeks", []), "blocks": blocks,
                    "planned": len(blocks), "authored": sum(1 for b in blocks if b["authored"]),
                    "taught": sum(1 for b in blocks if b["taught"])})
    return out


# ---------------------------------------------------------------- collect / render
def collect() -> dict:
    if not TRAINER.is_dir():
        raise TrainerMissing("trainer/ (private repo) is not cloned here; the tracker cannot be rebuilt without it")
    cur = bi.load_curriculum()
    config = json.loads((HARNESS / "config.json").read_text(encoding="utf-8"))
    metrics = json.loads((HARNESS / "metrics.json").read_text(encoding="utf-8"))
    plans = _plans()
    weeks = []
    for w in cur["weeks"]:
        ew = bi.expand_week(cur, w)
        pi = plans.get(w["week"])
        weeks.append({
            "week": w["week"], "dir": w["dir"], "theme": w["theme"], "phase": w["phase"], "project": w["project"],
            "start": ew["start"].isoformat(), "end": ew["end"].isoformat(),
            "plan": {"exists": bool(pi), "ok": bool(pi and pi["ok"]), "problems": pi["problems"] if pi else 0,
                     "path": pi["path"] if pi else f"harness/plans/week-{w['week']:02d}.md"},
            "days": [_day(cur, w, s, pi) for s in ew["slots"]],
        })
    return {
        "cohort": cur["cohort"], "siteTitle": cur["siteTitle"],
        "cal": {"startDate": cur["startDate"], "endDate": cur["endDate"], "timezone": cur["timezone"]},
        "phases": cur["phases"], "projects": cur["projects"],
        "rules": {k: v for k, v in (config.get("tracker") or {}).items() if not k.startswith("_")},
        "caps": {"dayMinutesMin": metrics["runbook"]["dayMinutesMin"], "dayMinutesMax": metrics["runbook"]["dayMinutesMax"]},
        "weeks": weeks,
        "threads": _threads(cur, config, plans),
        "status": parse_status(cur),
        "stages": parse_stages(),
        "decisions": parse_decisions(),
        "runs": load_runs(),
        "tests": load_last_tests(),
    }


def data_json(data: dict | None = None) -> str:
    return json.dumps(collect() if data is None else data, ensure_ascii=False, indent=1).replace("</", "<\\/")


def render(data: dict | None = None) -> str:
    return "\n".join([BEGIN, "<script>", GENERATED_MARK, "window.TRACKER = " + data_json(data) + ";", "</script>", END])


def splice(html: str, block: str) -> str:
    start = html.index(BEGIN)
    end = html.index(END) + len(END)
    return html[:start] + block + html[end:]


def expected(data: dict | None = None) -> str:
    """What tracker.html must contain: the committed shell with the data block filled in."""
    return splice(TEMPLATE.read_text(encoding="utf-8"), render(data))


def build(quiet: bool = False) -> bool:
    """Write tracker.html if it is missing or stale. Returns True when the file changed.
    No-op (False) without trainer/ or the template."""
    if not TEMPLATE.is_file() or not TRAINER.is_dir():
        if not quiet:
            print("tracker.html not rebuilt (template or trainer/ missing)", file=sys.stderr)
        return False
    new_html = expected()
    if TRACKER.is_file() and TRACKER.read_text(encoding="utf-8") == new_html:
        return False
    TRACKER.write_text(new_html, encoding="utf-8", newline="\n")
    return True


def main(argv: list[str]) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except Exception:
            pass
    try:
        data = collect()
    except TrainerMissing as e:
        print(str(e), file=sys.stderr)
        return 2
    if "--json" in argv:
        print(data_json(data))
        return 0
    if not TEMPLATE.is_file():
        print(f"{TEMPLATE} missing", file=sys.stderr)
        return 2
    shell = TEMPLATE.read_text(encoding="utf-8")
    if BEGIN not in shell or END not in shell:
        print(f"markers missing in {TEMPLATE}", file=sys.stderr)
        return 2
    new_html = expected(data)
    html = TRACKER.read_text(encoding="utf-8") if TRACKER.is_file() else None
    if "--check" in argv:
        if html is None:
            print("tracker.html is missing (it is a local, gitignored file) — run: python harness/build_tracker.py", file=sys.stderr)
            return 1
        if new_html != html:
            print("tracker.html is stale — run: python harness/build_tracker.py", file=sys.stderr)
            return 1
        print("tracker.html is in sync")
        return 0
    if new_html != html:
        TRACKER.write_text(new_html, encoding="utf-8", newline="\n")
        print("tracker.html created" if html is None else "tracker.html updated")
    else:
        print("tracker.html already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
