"""Series README (D-0055): trainer/week-WW/demos/README.md is rendered from the week plan by harness/series_readme.py,
never hand-edited; --check fails while the file is missing or stale."""

from __future__ import annotations

import shutil
import sys
import tempfile
import unittest
from pathlib import Path

from helpers import HARNESS, ROOT, TRAINER, curriculum

sys.path.insert(0, str(HARNESS))
import plan_check  # noqa: E402
import series_readme  # noqa: E402

PLANS = HARNESS / "plans"


def _planned_weeks():
    return [w for w in curriculum()["weeks"] if (PLANS / f"week-{w['week']:02d}.md").is_file()]


class SeriesReadmeTests(unittest.TestCase):
    def test_render_covers_every_section_and_walkthrough(self):
        for w in _planned_weeks():
            with self.subTest(week=w["week"]):
                text = series_readme.render(w["week"])
                plan = plan_check.load_plan(PLANS / f"week-{w['week']:02d}.md")
                for h in ("## Conventions", "## Ordered demo table", "## Cross-demo dependency graph", "## Stop points if splitting", "## Squeeze priorities",
                          "## Hard-stop rule", "## Scaffold bundle", "## Run prerequisites", "## Per-day shape", "## Anti-spoiler ledger",
                          "## Real-world framing"):
                    self.assertIn(h, text, f"README lacks {h}")
                for b in plan_check.week_blocks(plan):
                    self.assertIn(f"[`{b['name']}.md`]({b['name']}.md)", text, f"README does not link {b['name']}.md")
                    self.assertIn(b["stopPoint"][:40], text)
                self.assertIn("Generated by harness/series_readme.py", text)
                self.assertIn(plan["hardStop"][:60], text)

    def test_check_mode_sees_missing_and_stale(self):
        w = _planned_weeks()[0]
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            (root / "harness" / "plans").mkdir(parents=True)
            shutil.copy(PLANS / f"week-{w['week']:02d}.md", root / "harness" / "plans")
            shutil.copy(HARNESS / "config.json", root / "harness")
            self.assertTrue(any("missing" in p for p in series_readme.check(w["week"], root)))
            out = series_readme.write(w["week"], root)
            self.assertEqual([], series_readme.check(w["week"], root))
            out.write_text(out.read_text(encoding="utf-8") + "\nhand edit\n", encoding="utf-8")
            self.assertTrue(any("stale" in p for p in series_readme.check(w["week"], root)))

    def test_every_week_folder_on_disk_has_a_fresh_readme(self):
        if not TRAINER.exists():
            self.skipTest("trainer/ private repo not cloned here")
        for w in _planned_weeks():
            if (TRAINER / w["dir"] / "demos").is_dir():
                with self.subTest(week=w["week"]):
                    self.assertEqual([], series_readme.check(w["week"]))


if __name__ == "__main__":
    unittest.main()
